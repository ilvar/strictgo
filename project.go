// strictgo: capability
package main

import (
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
)

const skill = `---
name: strictgo
description: Check and fix Go projects with strictgo's deterministic JSON feedback.
---

# strictgo

Read the task and inspect the Go module before editing. Make the smallest coherent change. Run ` + "`strictgo check .`" + `, parse the JSON diagnostics, and resolve every error. Run ` + "`strictgo fix .`" + ` only for gofmt edits. Then run ` + "`go test ./...`" + ` and inspect the diff. Keep filesystem, network, and process calls in a file marked ` + "`// strictgo: capability`" + ` before its package clause. Handle errors and avoid panic, dot imports, and mutable package globals.
`

func createProject(name string) error {
	if !regexp.MustCompile(`^[a-z][a-z0-9_-]*$`).MatchString(name) {
		return errors.New("project name must start with a lowercase letter and contain only lowercase letters, digits, hyphens, or underscores")
	}
	if _, err := os.Lstat(name); err == nil {
		return fmt.Errorf("%s already exists", name)
	} else if !os.IsNotExist(err) {
		return err
	}
	files := map[string]string{
		"go.mod":                   "module example.com/" + name + "\n\ngo 1.23\n",
		"main.go":                  "package main\n\nimport \"fmt\"\n\nfunc main() {\n\tfmt.Println(\"Hello, " + name + "!\")\n}\n",
		"main_test.go":             "package main\n\nimport \"testing\"\n\nfunc TestMainPackage(t *testing.T) {\n\tif testing.Short() {\n\t\tt.Skip(\"short mode\")\n\t}\n}\n",
		".gitignore":               "/" + name + "\n/coverage.out\n",
		"README.md":                "# " + name + "\n\nGenerated by strictgo. Replace the example module path in `go.mod` before publishing.\n\n```sh\ngo fmt ./...\ngo vet ./...\ngo test ./...\nstrictgo check .\n```\n",
		"AGENTS.md":                "# Agent workflow\n\nRun `strictgo check .` after edits, resolve its JSON diagnostics, then run `go test ./...`. Place filesystem, network, and process operations in a file marked `// strictgo: capability` before `package`.\n",
		"Makefile":                 ".PHONY: check test fmt\ncheck:\n\tgo vet ./...\n\tgo test ./...\n\tstrictgo check .\ntest:\n\tgo test ./...\nfmt:\n\tgo fmt ./...\n",
		".github/workflows/ci.yml": "name: CI\non: [push, pull_request]\njobs:\n  check:\n    runs-on: ubuntu-latest\n    steps:\n      - uses: actions/checkout@v4\n      - uses: actions/setup-go@v5\n        with:\n          go-version-file: go.mod\n      - run: test -z \"$(gofmt -l .)\"\n      - run: go vet ./...\n      - run: go test ./...\n      - run: go install github.com/ilvar/strictgo@latest\n      - run: strictgo check .\n",
	}
	if err := os.Mkdir(name, 0755); err != nil {
		return err
	}
	for path, content := range files {
		full := filepath.Join(name, path)
		if err := os.MkdirAll(filepath.Dir(full), 0755); err != nil {
			return err
		}
		if err := os.WriteFile(full, []byte(content), 0644); err != nil {
			return err
		}
	}
	return nil
}
func installSkills() error {
	home, err := os.UserHomeDir()
	if err != nil {
		return err
	}
	type client struct{ name, detect, target string }
	clients := []client{{"Codex", ".codex", filepath.Join(home, ".agents", "skills", "strictgo", "SKILL.md")}, {"Claude Code", ".claude", filepath.Join(home, ".claude", "skills", "strictgo", "SKILL.md")}}
	found := 0
	var pending []client
	for _, c := range clients {
		_, dirErr := os.Stat(filepath.Join(home, c.detect))
		_, cmdErr := exec.LookPath(map[string]string{"Codex": "codex", "Claude Code": "claude"}[c.name])
		if dirErr != nil && cmdErr != nil {
			continue
		}
		found++
		prior, err := os.ReadFile(c.target)
		if err == nil {
			if string(prior) != skill {
				return fmt.Errorf("refusing to overwrite modified skill at %s", c.target)
			}
			continue
		}
		if !os.IsNotExist(err) {
			return err
		}
		pending = append(pending, c)
	}
	for _, c := range pending {
		if err := os.MkdirAll(filepath.Dir(c.target), 0755); err != nil {
			return err
		}
		if err := os.WriteFile(c.target, []byte(skill), 0644); err != nil {
			return err
		}
		_, _ = fmt.Fprintf(os.Stderr, "installed %s skill: %s\n", c.name, c.target)
	}

	if found == 0 {
		return errors.New("no supported agent installation detected")
	}
	return nil
}

package main

import (
	"errors"
	"regexp"

	"github.com/ilvar/strictgo/internal/capability"
)

const skill = `---
name: strictgo
description: Check and fix Go projects with strictgo's deterministic JSON feedback.
---

# strictgo

Inspect the Go module, make a small coherent change, and run ` + "`strictgo check .`" + `. Parse the JSON diagnostics and resolve every error. Use ` + "`strictgo fix .`" + ` for validated mechanical edits. Run ` + "`strictgo thorough .`" + ` when full tests, race detection, and bounded fuzzing are needed. Keep filesystem, network, and process operations in a dedicated package named ` + "`capability`" + `. Handle error-returning calls or explicitly discard their results. Avoid panic, dot imports, and mutable package globals.
`

func createProject(name string) error {
	if !regexp.MustCompile(`^[a-z][a-z0-9_-]*$`).MatchString(name) {
		return errors.New("project name must start with a lowercase letter and contain only lowercase letters, digits, hyphens, or underscores")
	}

	files := map[string]string{
		"go.mod":                   "module example.com/" + name + "\n\ngo 1.26.0\n",
		"main.go":                  "package main\n\nimport \"fmt\"\n\nfunc main() {\n\t_, _ = fmt.Println(\"Hello, " + name + "!\")\n}\n",
		"main_test.go":             "package main\n\nimport \"testing\"\n\nfunc TestMainPackage(t *testing.T) {\n\tif testing.Short() {\n\t\tt.Skip(\"short mode\")\n\t}\n}\n",
		".gitignore":               "/" + name + "\n/coverage.out\n",
		"README.md":                "# " + name + "\n\nGenerated by strictgo. Replace the example module path in `go.mod` before publishing.\n\n```sh\ngo fmt ./...\ngo vet ./...\ngo test ./...\nstrictgo check .\n```\n",
		"AGENTS.md":                "# Agent workflow\n\nRun `strictgo check .` after edits, resolve its JSON diagnostics, then run `go test ./...`. Use `strictgo thorough .` for full tests, race detection, and bounded fuzzing. Put filesystem, network, and process operations in a dedicated `capability` package.\n",
		"Makefile":                 ".PHONY: check thorough test fmt\ncheck:\n\tgo vet ./...\n\tgo test ./...\n\tstrictgo check .\nthorough:\n\tstrictgo thorough .\ntest:\n\tgo test ./...\nfmt:\n\tgo fmt ./...\n",
		".github/workflows/ci.yml": "name: CI\non: [push, pull_request]\njobs:\n  check:\n    runs-on: ubuntu-latest\n    steps:\n      - uses: actions/checkout@v4\n      - uses: actions/setup-go@v5\n        with:\n          go-version-file: go.mod\n      - run: test -z \"$(gofmt -l .)\"\n      - run: go vet ./...\n      - run: go test ./...\n      - run: go install github.com/ilvar/strictgo@latest\n      - run: strictgo thorough .\n",
	}
	return capability.CreateProject(name, files)
}
func installSkills() error { return capability.InstallSkills(skill) }
